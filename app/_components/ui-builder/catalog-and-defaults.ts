export const CATALOG_BY_TYPE: Record<UIComponentType, UICatalogEntry> = COMPONENT_CATALOG.reduce(
  (acc, item) => {
    acc[item.type] = item;
    return acc;
  },
  {} as Record<UIComponentType, UICatalogEntry>,
);

export function createCatalogElement(
  type: UIComponentType,
  x: number,
  y: number,
  componentIdPrefix = "app.ui",
): UICanvasElement {
  const entry = CATALOG_BY_TYPE[type];
  const id = newElementId(type.slice(0, 6));
  const cleanPrefix = componentIdPrefix.trim().replace(/\.$/, "") || "app.ui";
  return {
    id,
    type,
    name: entry.label,
    componentId: `${cleanPrefix}.${type}.${id.slice(-4)}`,
    x: Math.max(0, Math.round(x)),
    y: Math.max(0, Math.round(y)),
    width: entry.defaultWidth,
    height: entry.defaultHeight,
    locked: false,
    hidden: false,
    props: deepClone(entry.defaultProps),
    style: entry.defaultStyle ? deepClone(entry.defaultStyle) : undefined,
  };
}

